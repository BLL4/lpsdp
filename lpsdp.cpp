// When processing command line arguments, it is possible to scale the program
// It is nice to do it like  -s '4*3*7'  so one does not have to calculate it by hand.
double evaluate(const char * expr) 
{

    //cerr << "evaluating " << expr << endl;

    std::istringstream iss(expr);
    double result;
    iss >> result;

    char op;
    double num;
    while (iss >> op >> num) {
        switch (op) {
//           case '+': result += num; break;
//           case '-': result -= num; break;
            case '*': result *= num; break;
//            case '/': result /= num; break;
            default:
                throw std::runtime_error("Unknown operator");
        }
    }

    return result;
}


