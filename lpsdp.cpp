// This is for holding the semidefinite program in memory. 
// We need to be efficient
struct SDPBlock
{
    long long constraintID;
    std::vector<short int> rows;    // we try to save space a little on the rows and columns
    std::vector<short int> columns;
    std::vector<lp_value> values;
    std::unordered_map<int, lp_value> diagonal; // the diagonal blocks may be quite long
};

struct SDPProblem
{
    std::string filename;

    long long num_constraints;
    int num_blocks;
    lp_value constants_rescale;
    
    std::vector<int> block_sizes;
    std::vector<lp_value> constants;
    std::vector<double> t_coef;
    std::vector<std::vector<SDPBlock*> > blocks_all; // For all indexes
    std::vector<std::vector<SDPBlock*> > blocks_compressed;  // only the ones non-empty
};



struct Constraint
{
    std::unordered_map<long long, double> d;
    std::vector<double> v;
    int blockID;
    int inblockID = 0; // useful for original linear constraints

    std::vector<pair<int, double> >slacks; // pairs  iterationID / slack_value
    int   last_tight_iter = -1; // What iteratin was the last time constraint was tight
    bool  would_be_removed = false; // this is for debugging and seeing if we remove constraint that would be needed later

    string name = "";
    bool active = false; // If the constraint was tight the last time around
    double dual_weight = 0;
    bool from_input = false; // If the constraint was in the original model in input file
};

bool read_problem_file(SDPProblem &p, const std::string &filename, lp_value constants_rescale = 1) {

    cout << "Loading file " << filename << " with scale " << constants_rescale << " starts at " <<  timestamp() << endl;

    p.constants_rescale = constants_rescale;

    // Count total lines in the file
    // Fun but useless waste of time
    //long long total_lines = count_lines(filename);
    //if (total_lines < 0) {
    //    return false;  // Error already printed inside count_lines
    //}

    auto start_time = std::chrono::high_resolution_clock::now();

    // Open the file for reading with buffering
    std::ifstream file(filename);
    if (!file.is_open()) {
        std::cerr << "Error: Unable to open file " << filename << std::endl;
        return false;
    }

    //std::cout << "Opened file successfully, total lines: " << total_lines << " " <<  timestamp() << endl;
    std::cout << "Opened file successfully.  " <<  timestamp() << endl;


    p.filename = filename;

    // Continue with reading the first few lines
    file >> p.num_constraints >> p.num_blocks;  // Read first two integers

    // Read block sizes
    p.block_sizes.resize(p.num_blocks);
    for (int i = 0; i < p.num_blocks; ++i) {
        file >> p.block_sizes[i];
    }

    // Read constants 
    p.constants.reserve(p.num_constraints);
    double value_d;
    for (long long i = 0; i < p.num_constraints; ++i) {
        file >> value_d;
        p.constants.push_back(rescale_number(value_d, constants_rescale));
    }

    p.blocks_all.resize(p.num_blocks);
    for (int i = 0; i < p.num_blocks; ++i) {
        p.blocks_all[i].resize(p.num_constraints, nullptr);
    }
    p.blocks_compressed.resize(p.num_blocks);

    //cerr << "XX t_coef Resizing to " << p.num_constraints << endl;
    p.t_coef.resize(p.num_constraints, 0);


    while (file.good()) 
    {
        long long constraint;
        int block_num;
        int row;
        int column;
        double value_d;
        lp_value value;

        file >> constraint >> block_num >> row >> column >> value_d;

        if (!file.good() || file.eof())
        {
            break;
        }

        if( value_d == 0)
        {
            cerr << "Found 0 at " << constraint << " " << block_num << " " << row << " " << column << " " << value_d << endl;
            continue;
        }

        //cout << "X " << constraint << " " << block_num << " " << row << " " << column << " " <<  value_d << endl;

        if (constraint == 0)
        {
            continue;
        }

        // Adjust indices to 0-based
        constraint--;
        block_num--;
        row--;
        column--;


        int size = p.block_sizes[block_num];

        if (size < 0 && ( -size == p.num_constraints+1 || -size == p.num_constraints+2))
        {
            if (p.num_constraints == column)
            {   
                //cout << "t_coef for p.num_constraints == column " << value_d << endl;
                //p.t_coef[constraint] = abs(value_d)/constants_rescale;
                p.t_coef[constraint] = std::abs(value_d);
                //cerr << "t_coef[constraint]: " << constraint << " "  << p.t_coef[constraint] << endl;
            
            }
            else
            {
                //cerr << " ignoring " << constraint << " " << block_num << " " << row << " " << column << endl;
            }
            continue;
        }

        if (size > 0 && row != column)
        {
            value = rescale_number(value_d, 2*constants_rescale);
        }
        else
        {
            value = rescale_number(value_d, constants_rescale);
        }


        SDPBlock *block;
        if (p.blocks_all.size() < block_num)
        {
            cerr << "Something is going wrong" << endl;
            cerr << constraint << " ";
            cerr << block_num << " ";
            cerr << row << " ";
            cerr << column << " ";
            cerr << value_d << endl;
        }
        assert(p.blocks_all.size() > block_num);
        assert(p.blocks_all[block_num].size() > constraint);
        if (p.blocks_all[block_num][constraint] == nullptr)
        {
            block = new SDPBlock();
            block->constraintID = constraint;

            p.blocks_all[block_num][constraint] = block;
            p.blocks_compressed[block_num].push_back(block);
        }
        else
        {
            block = p.blocks_all[block_num][constraint];
        }
        if (size > 0)
        {
            assert(row <  numeric_limits<short int>::max());
            assert(column <  numeric_limits<short int>::max());
            block->rows.push_back(row);
            block->columns.push_back(column);
            block->values.push_back(value);
        }
        else
        {
            block->diagonal[row] = value;
        } 

    }

    file.close();

    std::cout << "File successfully loaded. " <<  timestamp() << endl;

    // Count variables
    int variables = 0;
    for (auto block_size : p.block_sizes)
    {
        if (block_size < 0 && ( -block_size != p.num_constraints+1 || -block_size != p.num_constraints+2))
        {
            variables += -block_size;
        }
        else if (block_size >= 0)
        {
            variables += block_size * (block_size-1)/2 + block_size;
        }
    }
    cerr << "SDP has " << p.num_constraints << " constraints and " << variables << " variables other than slacks" << endl;

    return true;
}



/*
For a vector  constraint_vectors (cv) calculates vector ds that is 
    ds_i = ( cv^T A_i cv)

Typicall application is that we want to make sure that cv is not a negative eigenvector of
Sum_i y_i A_i .   We add constraint  0 <=  cv^T ( Sum_i y_i  A_i) cv =  Sum_i y_i  (cv^T  A_i cv) = Sum_i y_i ds_i
    
*/
void get_ds_from_block(std::vector<SDPBlock*>& block, long long yrange, std::unordered_map<long long, double>& ds, std::vector<double>& constraint_vectors) {
    for (long long k = 0; k < yrange; ++k) {
        if (block[k] != nullptr) {            
            SDPBlock* B = block[k];

            double value = 0.0;
            for (size_t j = 0; j < B->rows.size(); ++j) {
                int r = B->rows[j];
                int c = B->columns[j];
                double Brc = B->values[j];
                value += constraint_vectors[r] * constraint_vectors[c] * Brc;
            }
            //value *= 2; // This is perhaps not needed
            if (std::abs(value) > 1e-12) {
                ds[k] = value;
                //cout << "D at " << k << "=" << value << endl;
            }
        }
    }
}


/*
For one block calculates   A = A_i * y_i 
and tries to find an eigenvector corresponding to the largest (in absolute value) negative eigenvalue.

The it calls get_ds_from_block to obtain the linear constraint on y_i

*/   
bool process_SDP_block(Constraint *new_constraint, std::vector<SDPBlock*>& block, int blocksize, int blockID, const std::vector<double>& yval, long long yrange, bool verbose) {

    assert(new_constraint != nullptr);

    if (blocksize < 0) return false;
    
    if (block.empty()) return false;
    
#ifdef DEBUG_PRINT    
    cout << "Processing block " << blockID << " of size " << blocksize << endl;
#endif

    // Construct the matrix A
    std::vector<double> A(blocksize * blocksize, 0.0);
    bool AisEmpty = true;

    for (size_t i = 0; i < yval.size(); ++i) {
        if (std::abs(yval[i]) < 1e-8) continue;
        if (block[i] != nullptr) {
            for (size_t j = 0; j < block[i]->rows.size(); ++j) {
                int r = block[i]->rows[j];
                int c = block[i]->columns[j];
                double v = block[i]->values[j] * yval[i];
                A[r * blocksize + c] += v;
                //if (r != c) 
                A[c * blocksize + r] += v;  // Ensure symmetry
            }
            AisEmpty = false;
        }
    }
    
    if (AisEmpty) return false;

    //cout << "A built for " << blockID << endl;

    // Perform eigen decomposition using LAPACK
    std::vector<double> eigvals(blocksize, 0.0);

    // Query optimal workspace size
    int lwork = -1;
    double work_query;
    int info;
    char jobz = 'V'; // Compute eigenvectors
    char uplo = 'U'; // Upper triangle of A is stored

    // Note that A will get reweritten by the eigenvectors
    dsyev_(&jobz, &uplo, &blocksize, A.data(), &blocksize, eigvals.data(), &work_query, &lwork, &info);
    if (info != 0) {
        std::cerr << "Error querying workspace size: " << info << std::endl;
        return 1;
    }

    lwork = static_cast<int>(work_query);
    std::vector<double> work(lwork);

    // Compute eigenvalues and eigenvectors
    dsyev_(&jobz, &uplo, &blocksize, A.data(), &blocksize, eigvals.data(), work.data(), &lwork, &info);
    if (info != 0) {
        std::cerr << "Error computing eigenvalues and eigenvectors: " << info << std::endl;
        return 1;
    }


    if (info != 0) {
        std::cerr << "Eigen decomposition failed." << std::endl;
        return false;
    }


    // Find the smallest eigenvalue and its corresponding eigenvector
    int min_index = 0;
    for (int i = 1; i < blocksize; ++i) {
        if (eigvals[i] < eigvals[min_index]) {
            min_index = i;
        }
        //cout << "Eigenvalue: " << eigvals[i] << endl;
    }
    double min_eigenvalue = eigvals[min_index];

#ifdef DEBUG_PRINT    
    cout << "Eigenvalues: ";
    for (int i = 0; i < blocksize; ++i) {
        cout << " " << eigvals[i];
    }
    cout << "\nMinimum " << min_eigenvalue << endl;
#endif


    //std::vector<double> new_constraint(blocksize);
    //for (int i = 0; i < blocksize; ++i) {
    //    //evec[i] = A[i * blocksize + min_index];
    //    evec[i] = A[min_index * blocksize + i];
    //}
    
    //cout << "Min eigenvalue " << min_eigenvalue << endl;
    //cout << "Min eigenvector ";
    //for (int i = 0; i < blocksize; ++i) {
    //    cout << " " << evec[i];
    //}
    //cout << endl;

    //if (min_eigenvalue < -0.000000001) {
    if (min_eigenvalue < 0) {

//#ifdef DEBUG_PRINT
//        cout << "Minimum " << min_eigenvalue << endl;
//#endif

        new_constraint->v.resize(blocksize);
        for (int i = 0; i < blocksize; ++i) {
            //evec[i] = A[i * blocksize + min_index];
            new_constraint->v[i] = A[min_index * blocksize + i];
        }        

        get_ds_from_block(block, yrange, new_constraint->d, new_constraint->v);
        new_constraint->blockID = blockID;
        return true;
    }
    return false;
}


